create table buillon.estabelecimento_imagem (
    id uuid primary key,
    id_estabelecimento integer not null references buillon.estabelecimento on delete cascade,
    tipo varchar(20) not null check (tipo in ('image/jpeg', 'image/png', 'image/webp')),
    dados bytea not null check (octet_length(dados) between 1 and 5242880)
);

create table buillon.estabelecimento_publicacao (
    id integer generated by default as identity primary key,
    id_estabelecimento integer not null references buillon.estabelecimento on delete cascade,
    comentario varchar(1000) not null check (length(btrim(comentario)) > 0),
    criado_em timestamptz not null default now()
);

create index imagem_estabelecimento on buillon.estabelecimento_imagem (id_estabelecimento);
create index publicacao_estabelecimento on buillon.estabelecimento_publicacao (id_estabelecimento, id desc);
revoke all on buillon.estabelecimento_imagem, buillon.estabelecimento_publicacao from public;
revoke all on sequence buillon.estabelecimento_publicacao_id_seq from public;

insert into buillon.categoria (nome_categoria)
select nome
from (values ('Brasileira'), ('Italiana'), ('Japonesa'), ('Lanches'), ('Café e doces'), ('Vegetariana'), ('Outra')) as iniciais(nome)
where not exists (
    select 1 from buillon.categoria c where lower(btrim(c.nome_categoria)) = lower(iniciais.nome)
);
