create schema buillon;
revoke all on schema buillon from public;

create table buillon.categoria (
    id_categoria integer generated by default as identity primary key,
    nome_categoria varchar(60) not null
);

create table buillon.cliente (
    id_cliente integer generated by default as identity primary key,
    nome varchar(100) not null,
    cpf varchar(11) not null unique,
    email varchar(100) not null,
    senha varchar(255) not null,
    data_cadastro timestamptz default now()
);

create unique index cliente_email_normalizado on buillon.cliente (lower(btrim(email)));

create table buillon.fornecedor (
    id_fornecedor integer generated by default as identity primary key,
    nome_responsavel varchar(100) not null,
    documento varchar(18) not null unique,
    email varchar(100),
    senha varchar(255)
);

create unique index fornecedor_email_normalizado on buillon.fornecedor (lower(btrim(email)));

create table buillon.estabelecimento (
    id_estabelecimento integer generated by default as identity primary key,
    id_fornecedor integer not null references buillon.fornecedor,
    id_categoria integer not null references buillon.categoria,
    nome_fantasia varchar(100) not null,
    cnpj varchar(14) unique nulls not distinct,
    telefone varchar(20),
    descricao text,
    status varchar(20) default 'Pendente'
);

create table buillon.endereco (
    id_endereco integer generated by default as identity primary key,
    id_estabelecimento integer not null references buillon.estabelecimento,
    rua varchar(100),
    numero varchar(100),
    bairro varchar(50),
    cidade varchar(50),
    estado varchar(2),
    cep varchar(8)
);

create table buillon.nps (
    id_nps integer generated by default as identity primary key,
    id_cliente integer not null references buillon.cliente,
    id_estabelecimento integer not null references buillon.estabelecimento,
    nps_geral integer check (nps_geral between 1 and 5),
    nps_nota integer check (nps_nota between 0 and 10),
    comentario text,
    data_avaliacao timestamptz default now()
);

create unique index nps_avaliacao_por_cliente on buillon.nps (id_cliente, id_estabelecimento)
    where nps_geral is not null;

create table buillon.buillon_app_perfil (
    id_cliente integer primary key references buillon.cliente on delete cascade,
    bio varchar(160) not null,
    avatar varchar(255) not null
);

create table buillon.buillon_app_favorito (
    id_cliente integer references buillon.cliente on delete cascade,
    id_estabelecimento integer references buillon.estabelecimento on delete cascade,
    primary key (id_cliente, id_estabelecimento)
);

create table buillon.buillon_app_cardapio (
    id_item integer generated by default as identity primary key,
    id_estabelecimento integer not null references buillon.estabelecimento on delete cascade,
    nome varchar(100) not null,
    descricao varchar(300) not null,
    preco numeric(10,2) not null check (preco > 0),
    imagem varchar(500) not null
);

create table buillon.buillon_app_foto (
    id_foto integer generated by default as identity primary key,
    id_estabelecimento integer not null references buillon.estabelecimento on delete cascade,
    url varchar(500) not null,
    legenda varchar(150) not null
);

create index estabelecimento_fornecedor on buillon.estabelecimento (id_fornecedor);
create index estabelecimento_categoria on buillon.estabelecimento (id_categoria);
create index endereco_estabelecimento on buillon.endereco (id_estabelecimento, id_endereco);
create index nps_cliente on buillon.nps (id_cliente);
create index nps_estabelecimento on buillon.nps (id_estabelecimento);
create index favorito_estabelecimento on buillon.buillon_app_favorito (id_estabelecimento);
create index cardapio_estabelecimento on buillon.buillon_app_cardapio (id_estabelecimento, id_item);
create index foto_estabelecimento on buillon.buillon_app_foto (id_estabelecimento, id_foto);

create function buillon.ranking_estabelecimentos()
returns table (
    id_estabelecimento integer,
    nome_fantasia varchar,
    nome_categoria varchar,
    total_avaliacoes bigint,
    media_avaliacao numeric,
    posicao bigint
)
language sql
stable
security invoker
set search_path = ''
as $$
    select e.id_estabelecimento, e.nome_fantasia, c.nome_categoria,
        count(n.id_nps), round(avg(n.nps_geral), 2),
        row_number() over (
            order by avg(n.nps_geral) desc, count(n.id_nps) desc, e.nome_fantasia, e.id_estabelecimento
        )
    from buillon.estabelecimento e
    join buillon.categoria c using (id_categoria)
    join buillon.nps n using (id_estabelecimento)
    where n.nps_geral is not null
    group by e.id_estabelecimento, c.nome_categoria
    order by avg(n.nps_geral) desc, count(n.id_nps) desc, e.nome_fantasia, e.id_estabelecimento
    limit 10
$$;

