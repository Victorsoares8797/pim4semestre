USE [BUILLON];
GO

IF OBJECT_ID(N'dbo.BUILLON_APP_PERFIL', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BUILLON_APP_PERFIL (
        ID_CLIENTE int NOT NULL PRIMARY KEY REFERENCES dbo.CLIENTE(ID_CLIENTE) ON DELETE CASCADE,
        BIO nvarchar(160) NOT NULL,
        AVATAR nvarchar(255) NOT NULL
    );
END;
GO

IF OBJECT_ID(N'dbo.BUILLON_APP_CARDAPIO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BUILLON_APP_CARDAPIO (
        ID_ITEM int IDENTITY PRIMARY KEY,
        ID_ESTABELECIMENTO int NOT NULL REFERENCES dbo.ESTABELECIMENTO(ID_ESTABELECIMENTO) ON DELETE CASCADE,
        NOME nvarchar(100) NOT NULL,
        DESCRICAO nvarchar(300) NOT NULL,
        PRECO decimal(10,2) NOT NULL CHECK (PRECO > 0),
        IMAGEM nvarchar(500) NOT NULL
    );
END;
GO

IF OBJECT_ID(N'dbo.BUILLON_APP_FOTO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BUILLON_APP_FOTO (
        ID_FOTO int IDENTITY PRIMARY KEY,
        ID_ESTABELECIMENTO int NOT NULL REFERENCES dbo.ESTABELECIMENTO(ID_ESTABELECIMENTO) ON DELETE CASCADE,
        URL nvarchar(500) NOT NULL,
        LEGENDA nvarchar(150) NOT NULL
    );
END;
GO

IF OBJECT_ID(N'dbo.BUILLON_APP_FAVORITO', N'U') IS NULL
BEGIN
    CREATE TABLE dbo.BUILLON_APP_FAVORITO (
        ID_CLIENTE int NOT NULL REFERENCES dbo.CLIENTE(ID_CLIENTE) ON DELETE CASCADE,
        ID_ESTABELECIMENTO int NOT NULL REFERENCES dbo.ESTABELECIMENTO(ID_ESTABELECIMENTO) ON DELETE CASCADE,
        PRIMARY KEY (ID_CLIENTE, ID_ESTABELECIMENTO)
    );
END;
GO
